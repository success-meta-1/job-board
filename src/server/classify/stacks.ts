export function extractStacks(...texts: (string | undefined)[]): string[] {
  const text = texts.filter(Boolean).join('\n');
  if (!text) return [];
  return STACK_PATTERNS.filter(([, re]) => re.test(text)).map(([name]) => name);
}

export const ALL_STACKS = STACK_PATTERNS.map(([name]) => name);
